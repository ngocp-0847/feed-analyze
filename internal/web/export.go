// siteMarker đánh dấu thư mục do fa tạo — Export chỉ xoá thư mục có marker này.
const siteMarker = ".fa-site"

type ExportStats struct {
	Pages, Assets, Dailies, Stories, Deeps int
	Bytes                                  int64
}

type pageEntry struct {
	path    string // đường dẫn route (không có "/" cuối), vd /r/2026-10-10
	updated string // YYYY-MM-DD cho sitemap
}

// Export dựng site tĩnh công khai vào dir (xoá nội dung cũ nếu dir do fa tạo).
func (s *Server) Export(dir string) (ExportStats, error) {
	var st ExportStats
	if !s.public() {
		return st, errors.New("Export cần server ở chế độ public (NewPublic)")
	}
	if err := prepareDir(dir); err != nil {
		return st, err
	}
	h := s.Handler()

	pages := []pageEntry{{"/", ""}, {"/dashboard", ""}, {"/stories", ""}, {"/deep", ""}}
	for _, n := range []int{7, 30, 90} {
		pages = append(pages, pageEntry{fmt.Sprintf("/dashboard/%d", n), ""})
	}
	if s.secVisible() {
		pages = append(pages, pageEntry{"/security", ""})
		for _, n := range []int{7, 30, 90} {
			pages = append(pages, pageEntry{fmt.Sprintf("/security/%d", n), ""})
		}
	}
	dates := s.latestDates(100000)
	for _, d := range dates {
		pages = append(pages, pageEntry{"/r/" + d, d})
		st.Dailies++
	}
	since := ""
	if s.Pub.Since != "" {
		since = s.Pub.Since
	}
	sls, err := s.st.Storylines("", since, 100000)
	if err != nil {
		return st, err
	}
	for _, sl := range sls {
		if s.hidden(sl.Slug) {
			continue
		}
		pages = append(pages, pageEntry{"/s/" + sl.Slug, sl.LastDate})
		st.Stories++
	}
	deeps := s.deepReports(100000)
	for _, rp := range deeps {
		pages = append(pages, pageEntry{DeepURL(rp.Date, strings.TrimPrefix(rp.Kind, "deep:")), rp.Date})
		st.Deeps++
	}

	for _, p := range pages {
		body, err := fetch(h, p.path)
		if err != nil {
			return st, err
		}
		out := filepath.Join(dir, filepath.FromSlash(strings.TrimPrefix(p.path, "/")), "index.html")
		if err := writeFile(out, body, &st); err != nil {
			return st, err
		}
		st.Pages++
	}

	// 404
	rec := httptest.NewRecorder()
	s.render(rec, httptest.NewRequest(http.MethodGet, "/404", nil), "", "Không tìm thấy",
		`<h1>Không tìm thấy trang</h1><p>Trang này không tồn tại hoặc đã bị gỡ. <a href="/">Về trang chủ</a>.</p>`)
	if err := writeFile(filepath.Join(dir, "404.html"), rec.Body.Bytes(), &st); err != nil {
		return st, err
	}

	// static
	sub, _ := fs.Sub(staticFS, "static")
	err = fs.WalkDir(sub, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := fs.ReadFile(sub, p)
		if err != nil {
			return err
		}
		st.Assets++
		return writeFile(filepath.Join(dir, "static", filepath.FromSlash(p)), b, &st)
	})
	if err != nil {
		return st, err
	}

	if err := writeFile(filepath.Join(dir, "feed.xml"), s.atom(dates, deeps), &st); err != nil {
		return st, err
	}
	if err := writeFile(filepath.Join(dir, "sitemap.xml"), s.sitemap(pages), &st); err != nil {
		return st, err
	}
	robots := "User-agent: *\nAllow: /\n"
	if s.Pub.BaseURL != "" {
		robots += "Sitemap: " + s.Pub.BaseURL + "/sitemap.xml\n"
	}
	if err := writeFile(filepath.Join(dir, "robots.txt"), []byte(robots), &st); err != nil {
		return st, err
	}
	headers := `/static/*
  Cache-Control: public, max-age=86400
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
`
	if err := writeFile(filepath.Join(dir, "_headers"), []byte(headers), &st); err != nil {
		return st, err
	}
	// Workers Static Assets: không đưa file đánh dấu nội bộ lên web
	if err := writeFile(filepath.Join(dir, ".assetsignore"), []byte(siteMarker+"\n"), &st); err != nil {
		return st, err
	}
	return st, nil
}

func fetch(h http.Handler, p string) ([]byte, error) {
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, p, nil))
	if rec.Code != http.StatusOK {
		return nil, fmt.Errorf("render %s: HTTP %d", p, rec.Code)
	}
	return rec.Body.Bytes(), nil
}

func writeFile(p string, b []byte, st *ExportStats) error {
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	st.Bytes += int64(len(b))
	return os.WriteFile(p, b, 0o644)
}

// prepareDir: tạo mới dir; nếu đã có thì chỉ xoá khi có marker của fa (tránh xoá nhầm thư mục người dùng).
func prepareDir(dir string) error {
	ents, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dir, siteMarker), []byte("generated by fa publish\n"), 0o644)
	}
	if err != nil {
		return err
	}
	if len(ents) > 0 {
		if _, err := os.Stat(filepath.Join(dir, siteMarker)); err != nil {
			return fmt.Errorf("thư mục %s đã có nội dung không do fa tạo — chọn thư mục khác (publish.out_dir)", dir)
		}
		for _, e := range ents {
			if e.Name() == siteMarker {
				continue
			}
			if err := os.RemoveAll(filepath.Join(dir, e.Name())); err != nil {
				return err
			}
		}
	}
	return os.WriteFile(filepath.Join(dir, siteMarker), []byte("generated by fa publish\n"), 0o644)
}

// ---------- Atom feed ----------

type atomFeed struct {
	XMLName xml.Name    `xml:"feed"`
	NS      string      `xml:"xmlns,attr"`
	Title   string      `xml:"title"`
	Sub     string      `xml:"subtitle,omitempty"`
	ID      string      `xml:"id"`
	Updated string      `xml:"updated"`
	Links   []atomLink  `xml:"link"`
	Author  atomAuthor  `xml:"author"`
	Entries []atomEntry `xml:"entry"`
}

type atomLink struct {
	Href string `xml:"href,attr"`
	Rel  string `xml:"rel,attr,omitempty"`
}

type atomAuthor struct {
	Name string `xml:"name"`
}

type atomEntry struct {
	Title   string   `xml:"title"`
	ID      string   `xml:"id"`
	Link    atomLink `xml:"link"`
	Updated string   `xml:"updated"`
	Summary string   `xml:"summary"`
}

func (s *Server) abs(p string) string { return s.Pub.BaseURL + s.link(p) }

func (s *Server) atom(dates []string, deeps []store.Report) []byte {
	f := atomFeed{NS: "http://www.w3.org/2005/Atom", Title: s.Pub.SiteTitle, Sub: s.Pub.Description, ID: s.abs("/"),
		Updated: time.Now().UTC().Format(time.RFC3339), Author: atomAuthor{Name: s.Pub.SiteTitle},
		Links: []atomLink{{Href: s.abs("/")}, {Href: s.Pub.BaseURL + "/feed.xml", Rel: "self"}}}
	for i, d := range dates {
		if i >= 30 {
			break
		}
		dl, _ := analyze.LoadDaily(s.st, d)
		if dl == nil {
			continue
		}
		title, sum := "Bản tin "+d, ""
		if dl.Synthesis != nil {
			if dl.Synthesis.Title != "" {
				title = dl.Synthesis.Title + " (" + d + ")"
			}
			sum = strings.Join(dl.Synthesis.TLDR, "\n• ")
			if sum != "" {
				sum = "• " + sum
			}
		}
		u := s.abs("/r/" + d)
		f.Entries = append(f.Entries, atomEntry{Title: title, ID: u, Link: atomLink{Href: u}, Updated: d + "T07:00:00+07:00", Summary: sum})
	}
	for i, rp := range deeps {
		if i >= 20 {
			break
		}
		slug := strings.TrimPrefix(rp.Kind, "deep:")
		title, sum := "Phân tích sâu: "+slug, ""
		if v, _ := research.LoadViz(s.st, rp.Date, rp.Kind); v != nil && v.Headline != "" {
			title, sum = "Phân tích sâu: "+trunc(v.Headline, 120), v.Headline
		}
		u := s.abs(DeepURL(rp.Date, slug))
		f.Entries = append(f.Entries, atomEntry{Title: title, ID: u, Link: atomLink{Href: u}, Updated: rp.CreatedAt.UTC().Format(time.RFC3339), Summary: sum})
	}
	b, _ := xml.MarshalIndent(f, "", "  ")
	return append([]byte(xml.Header), b...)
}

func (s *Server) sitemap(pages []pageEntry) []byte {
	var b strings.Builder
	b.WriteString(xml.Header + `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">` + "\n")
	for _, p := range pages {
		fmt.Fprintf(&b, "  <url><loc>%s</loc>", xmlEsc(s.abs(p.path)))
		if p.updated != "" {
			fmt.Fprintf(&b, "<lastmod>%s</lastmod>", p.updated)
		}
		b.WriteString("</url>\n")
	}
	b.WriteString("</urlset>\n")
	return []byte(b.String())
}

func xmlEsc(s string) string {
	var b strings.Builder
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}
